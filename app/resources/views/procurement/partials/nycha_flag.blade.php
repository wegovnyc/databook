<x-db.alert tone="info" class="mb-4">
    <strong>Why NYCHA procurement looks different.</strong>
    The New York City Housing Authority is a separate public authority — not a
    mayoral agency — and is largely federally funded (U.S. HUD). It reports to
    <a href="https://www.checkbooknyc.com" target="_blank" rel="noopener">Checkbook NYC</a>
    through its own dedicated feeds, so NYCHA does not appear in the City's standard
    contracts, solicitations, and vendor registry that power other agencies'
    procurement pages. Instead, Databook surfaces NYCHA's own Budget, Revenue,
    Contracts, and Spending domains below. (Checkbook data begins FY2018, and
    NYCHA's expense budget is reported committed-forward.)
</x-db.alert>
